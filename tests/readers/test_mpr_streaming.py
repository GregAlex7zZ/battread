def test_mixed_accessory_widths_preserve_wire_offsets() -> None:
    """Mixed-width skips and shared flags preserve independently encoded values."""
    from galvani import BioLogic  # pyright: ignore[reportMissingImports]

    identifiers = [115, 1, 4, 175, 2, 116, 8, 176, 182, 177, 6, 215]
    dtype = binary._record_dtype(identifiers, cast(binary.GalvaniSchema, BioLogic))
    wire = (
        b"\xff" * 8
        + struct.pack("<Bd", 3, 10.0)
        + b"\xff" * 12
        + struct.pack("<f", -2.0)
        + b"\xff" * 16
        + struct.pack("<f", 3.5)
        + b"\xff" * 4
    )
    assert dtype.itemsize == len(wire)
    record = np.frombuffer(wire, dtype=dtype)[0]
    assert record["time/s"] == 10.0
    assert record["I/mA"] == -2.0
    assert record["Ewe/V"] == 3.5
    assert record["flags"] == 3
    assert all(
        identifier not in BioLogic.VMPdata_colID_dtype_map
        for identifier in (115, 116, 175, 176, 177, 182, 215)
    )


def test_header_seek_arithmetic_uses_python_ints(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Seeking past large modules must not wrap NumPy uint32 header lengths."""
    offsets: list[int] = []

    class HeaderBackend:
        """Simulate yield-before-seek metadata without allocating a huge file."""

        def read_VMP_modules(
            self, stream: BinaryIO, read_module_data: bool = True
        ) -> Generator[dict[str, object], None, None]:
            """Require normalized integer fields before the generator resumes."""
            assert read_module_data is False
            for name, offset, length in (
                (b"extra", 100, 2**32 - 1),
                (b"VMP Set   ", 2**32 + 200, 0),
                (b"VMP data  ", 2**32 + 300, 0),
            ):
                description: dict[str, object] = {
                    "shortname": name,
                    "offset": offset,
                    "length": np.uint32(length),
                    "version": 0,
                    "date": b"01/01/24",
                }
                yield description
                left, right = description["offset"], description["length"]
                assert isinstance(left, int) and isinstance(right, int)
                offsets.append(left + right)

    def stamp(stream: BinaryIO) -> tuple[int, int, int, int]:
        """Provide virtual large-file bounds without allocating disk space or RAM."""
        return (0, 0, 2**32 + 4096, 0)

    monkeypatch.setattr(binary, "_stamp", stamp)
    modules = binary._metadata(
        BytesIO(binary.MPR_MAGIC), cast(binary.GalvaniSchema, HeaderBackend())
    )
    assert len(modules) == 2
    assert offsets[0] == 2**32 + 99


