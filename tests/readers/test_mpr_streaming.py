def wire_module(
    name: bytes, version: int, payload: bytes, modern: bool = False
) -> bytes:
    """Write a known v1/v2 module header independently of Galvani's definitions."""
    if modern:
        header = struct.pack(
            "<10s25sIIII8s",
            name,
            name,
            0xFFFFFFFF,
            len(payload),
            version,
            11,
            b"01/01/24",
        )
    else:
        header = struct.pack(
            "<10s25sII8s", name, name, len(payload), version, b"01/01/24"
        )
    return b"MODULE" + header + payload


def wire_source(
    path: Path,
    version: int = 2,
    modern: bool = False,
    paired_v0: bool = False,
    times: tuple[float, ...] = (10.0, 11.0, 13.0),
) -> Path:
    """Encode independent time/current/voltage records in supported data layouts."""
    ids = (4, 8, 6)
    initial = struct.pack("<IB", len(times), len(ids))
    if version == 0:
        if paired_v0:
            header = initial + bytes((0, 4, 0, 8, 0, 6))
            header = header.ljust(1007, b"\x00")
        else:
            header = (initial + bytes(ids)).ljust(100, b"\x00")
    else:
        header = initial + struct.pack("<HHH", *ids)
        header = header.ljust(406 if version == 3 else 405, b"\x00")
    records = b"".join(
        struct.pack("<dff", time, -2.0 if index % 2 == 0 else 3.0, 3.5)
        for index, time in enumerate(times)
    )
    path.write_bytes(
        binary.MPR_MAGIC
        + wire_module(b"VMP Set   ", 0, b"", modern)
        + wire_module(b"VMP data  ", version, header + records, modern)
    )
    return path


@pytest.mark.parametrize("modern", [False, True])
@pytest.mark.parametrize(
    "version,paired", [(0, False), (0, True), (2, False), (3, False)]
)
@pytest.mark.parametrize("chunk", [1, 2, 100_000])
def test_known_layouts_match_encoded_values_and_galvani(
    tmp_path: Path, modern: bool, version: int, paired: bool, chunk: int
) -> None:
    """Both module headers and all data versions preserve signs and exact timing."""
    from galvani import BioLogic  # pyright: ignore[reportMissingImports]

    source = wire_source(tmp_path / "synthetic.mpr", version, modern, paired)
    expected = pd.DataFrame(
        {
            "time_s": [0.0, 1.0, 3.0],
            "current_mA": [-2.0, 3.0, -2.0],
            "voltage_V": [3.5] * 3,
        }
    )
    pd.testing.assert_frame_equal(read(source), expected)
    chunks = list(iter_read(source, chunk_size=chunk))
    pd.testing.assert_frame_equal(pd.concat(chunks, ignore_index=True), expected)
    layout = adapter._load_mpr(source)
    actual = np.concatenate(list(layout.iter_arrays(2)))
    with source.open("rb") as stream:
        legacy = BioLogic.MPRfile(stream)
    np.testing.assert_array_equal(actual, legacy.data)


def test_no_full_backend_constructor_is_used(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Inspection and conversion must work when full-memory parsing is forbidden."""
    from galvani import BioLogic  # pyright: ignore[reportMissingImports]

    def forbidden(*args: object, **kwargs: object) -> None:
        """Fail immediately if the old full-acquisition allocation path is invoked."""
        raise AssertionError("Full-memory constructor must not be called")

    monkeypatch.setattr(BioLogic, "MPRfile", forbidden)
    source = wire_source(tmp_path / "bounded.mpr")
    assert inspect(source).reader == "biologic-mpr"
    assert sum(len(frame) for frame in iter_read(source, chunk_size=1)) == 3
    result = convert(source, tmp_path / "result.parquet", chunk_size=1)
    pd.testing.assert_frame_equal(read(result), read(source))
    assert adapter.BioLogicMPRReader.capabilities.streaming


def test_binary_read_counts_are_bounded(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A huge requested chunk cannot disable the binary-byte buffer cap."""
    source = wire_source(
        tmp_path / "bounded.mpr", times=tuple(float(i) for i in range(25))
    )
    layout = adapter._load_mpr(source)
    monkeypatch.setattr(binary, "_MAX_BINARY_BYTES", 3 * layout.dtype.itemsize)
    arrays = list(layout.iter_arrays(1_000_000))
    assert [len(array) for array in arrays] == [3] * 8 + [1]
    assert all(array.nbytes <= 3 * layout.dtype.itemsize for array in arrays)


def test_inspection_reads_only_bounded_metadata(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Inspection must seek over large payloads instead of copying their contents."""
    source = wire_source(tmp_path / "bounded.mpr")
    original = binary._prefix
    requests: list[int] = []

    def counted(stream: BinaryIO, module: binary._Module, length: int) -> bytes:
        """Observe the size of each explicitly bounded metadata prefix request."""
        requests.append(length)
        return original(stream, module, length)

    monkeypatch.setattr(binary, "_prefix", counted)
    inspect(source)
    assert requests == [6, 405]


@pytest.mark.parametrize(
    "mutation",
    ["truncate", "extra", "count", "padding", "duplicate", "tail", "version"],
)
def test_corrupt_container_is_rejected_before_values(
    tmp_path: Path, mutation: str
) -> None:
    """Invalid framing/counts/reserved bytes must never silently omit rows."""
    source = wire_source(tmp_path / "bad.mpr")
    contents = bytearray(source.read_bytes())
    data_header = len(binary.MPR_MAGIC) + 6 + 51 + 6
    data_offset = data_header + 51
    if mutation == "truncate":
        contents = contents[:-1]
    elif mutation == "extra":
        contents += b"\x00"
    elif mutation == "count":
        struct.pack_into("<I", contents, data_offset, 4)
    elif mutation == "padding":
        contents[data_offset + 20] = 1
    elif mutation == "duplicate":
        contents += wire_module(b"VMP Set   ", 0, b"")
    elif mutation == "tail":
        contents += b"MODULE"
    else:
        struct.pack_into("<I", contents, data_header + 39, 99)
    source.write_bytes(contents)
    with pytest.raises(CorruptedFileError):
        inspect(source)


def test_source_mutation_after_inspection_is_rejected(tmp_path: Path) -> None:
    """A replaced/truncated acquisition cannot be read using stale metadata."""
    source = wire_source(tmp_path / "mutable.mpr")
    layout = adapter._load_mpr(source)
    source.write_bytes(source.read_bytes()[:-1])
    with pytest.raises(CorruptedFileError, match="changed"):
        next(layout.iter_arrays(1))


def test_iterator_close_releases_windows_file_handle(tmp_path: Path) -> None:
    """Cancellation after a yielded chunk releases the source for Windows cleanup."""
    source = wire_source(tmp_path / "cancel.mpr")
    iterator = cast(
        Generator[pd.DataFrame, None, None], iter_read(source, chunk_size=1)
    )
    assert len(next(iterator)) == 1
    iterator.close()
    source.unlink()
    assert not source.exists()


def test_late_backward_time_keeps_conversion_atomic(tmp_path: Path) -> None:
    """A late scientific failure must not publish any partially converted file."""
    source = wire_source(tmp_path / "bad-time.mpr", times=(10.0, 11.0, 9.0))
    target = tmp_path / "result.parquet"
    with pytest.raises(NonMonotonicTimeError):
        convert(source, target, chunk_size=1)
    assert not target.exists()


def test_missing_current_is_retained_across_binary_batches(tmp_path: Path) -> None:
    """Missing measured current must remain missing across binary batches."""
    source = wire_source(tmp_path / "missing.mpr")
    contents = bytearray(source.read_bytes())
    current_offset = len(binary.MPR_MAGIC) + 2 * (6 + 51) + 405 + 16 + 8
    struct.pack_into("<f", contents, current_offset, float("nan"))
    source.write_bytes(contents)
    with pytest.warns(MissingValueWarning):
        frames = list(iter_read(source, chunk_size=1))
    assert np.isnan(frames[1].current_mA.iloc[0])
    assert sum(len(frame) for frame in frames) == 3


def test_unknown_field_is_not_guessed_from_record_length(tmp_path: Path) -> None:
    """An upstream-unverified field must fail even when a width might seem plausible."""
    header = (struct.pack("<IBHH", 1, 2, 4, 999)).ljust(405, b"\x00")
    source = tmp_path / "unsupported.mpr"
    source.write_bytes(
        binary.MPR_MAGIC
        + wire_module(b"VMP Set   ", 0, b"")
        + wire_module(b"VMP data  ", 2, header + struct.pack("<df", 0.0, 3.0))
    )
    with pytest.raises(UnsupportedFormatError, match="999"):
        inspect(source)


@pytest.mark.parametrize("position", [0, 1, 2, 3])
@pytest.mark.parametrize("version", [0, 2, 3])
@pytest.mark.parametrize(
    "identifier,width",
    [(115, 8), (116, 8), (175, 4), (176, 4), (177, 4), (182, 8), (215, 4)],
)
def test_verified_field_is_opaque_and_never_selected(
    tmp_path: Path, position: int, version: int, identifier: int, width: int
) -> None:
    """Verified opaque bytes may precede canonical fields without shifting values.

    Non-numeric bytes ensure the counter-electrode field is never parsed as
    current or voltage. Synthetic struct encoding is independent of the reader.
    """
    ids = [4, 8, 6]
    ids.insert(position, identifier)
    header = struct.pack("<IB", 3, len(ids))
    if version == 0:
        header = (header + bytes(ids)).ljust(100, b"\x00")
    else:
        header = (header + struct.pack("<4H", *ids)).ljust(
            405 if version == 2 else 406, b"\x00"
        )
    records = bytearray()
    for time, current, voltage in [
        (10.0, -2.0, 3.5),
        (11.0, 3.0, 3.6),
        (13.0, -4.0, 3.7),
    ]:
        cells = [
            struct.pack("<d", time),
            struct.pack("<f", current),
            struct.pack("<f", voltage),
        ]
        cells.insert(position, b"\xff" * width)
        records.extend(b"".join(cells))
    source = tmp_path / "opaque.mpr"
    source.write_bytes(
        binary.MPR_MAGIC
        + wire_module(b"VMP Set   ", 0, b"")
        + wire_module(b"VMP data  ", version, header + records)
    )
    expected = pd.DataFrame(
        {
            "time_s": [0.0, 1.0, 3.0],
            "current_mA": [-2.0, 3.0, -4.0],
            "voltage_V": [float(np.float32(v)) for v in (3.5, 3.6, 3.7)],
        }
    )
    pd.testing.assert_frame_equal(read(source), expected)
    pd.testing.assert_frame_equal(
        pd.concat(iter_read(source, chunk_size=1), ignore_index=True), expected
    )
    assert len(inspect(source).columns) == len(
        inspect(wire_source(tmp_path / "known.mpr")).columns
    )


def test_opaque_215_preserves_shared_flags_and_duplicate_names() -> None:
    """Inserted opaque fields must not duplicate packed flag bytes or rename current."""
    from galvani import BioLogic  # pyright: ignore[reportMissingImports]

    dtype = binary._record_dtype(
        [1, 215, 2, 8, 215, 215, 8, 215], cast(binary.GalvaniSchema, BioLogic)
    )
    assert dtype.names == (
        "flags",
        "_ignored_mpr_215_1",
        "I/mA",
        "_ignored_mpr_215_2",
        "_ignored_mpr_215_3",
        "I/mA 2",
        "_ignored_mpr_215_4",
    )
    assert dtype.itemsize == 25
    assert BioLogic.VMPdata_colID_dtype_map.get(215) is None


